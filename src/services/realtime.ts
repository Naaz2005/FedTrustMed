/*
 * FedTrustMed Real-Time / Multi-Tab Synchronization
 *
 * Uses the browser BroadcastChannel API.
 *
 * This allows two FedTrustMed tabs opened in the same browser
 * to notify each other when important application data changes.
 *
 * Example:
 *
 * Tab 1 → Admin approves user
 *       ↓
 * BroadcastChannel
 *       ↓
 * Tab 2 → receives DATA_CHANGED
 *       ↓
 * Dashboard refreshes
 */

export const FEDTRUSTMED_CHANNEL_NAME =
  'fedtrustmed_realtime';

export type RealtimeEventType =
  | 'DATA_CHANGED'
  | 'AUTH_CHANGED'
  | 'LOGOUT';

export interface RealtimeEvent {
  type: RealtimeEventType;

  /*
   * Optional description of what changed.
   *
   * Examples:
   * USER_APPROVED
   * USER_REJECTED
   * PERMISSIONS_UPDATED
   * CONSENT_GRANTED
   * CONSENT_REVOKED
   * MEDICAL_RECORD_CREATED
   * TRUST_SCORE_CHANGED
   */
  action?: string;

  /*
   * Used to avoid processing our own events.
   */
  sourceId: string;

  timestamp: number;
}

/*
 * Every browser tab gets a unique ID.
 */
const SOURCE_ID =
  `${Date.now()}-${Math.random()
    .toString(36)
    .slice(2)}`;

/*
 * Create the BroadcastChannel only in the browser.
 *
 * This prevents problems if Vite/TypeScript evaluates
 * the module in an environment where window is unavailable.
 */
const channel =
  typeof window !== 'undefined' &&
  typeof BroadcastChannel !== 'undefined'
    ? new BroadcastChannel(FEDTRUSTMED_CHANNEL_NAME)
    : null;

/*
 * Send an event to all other FedTrustMed tabs.
 */
export const broadcastRealtimeEvent = (
  type: RealtimeEventType,
  action?: string
): void => {
  if (!channel) {
    return;
  }

  const event: RealtimeEvent = {
    type,
    action,
    sourceId: SOURCE_ID,
    timestamp: Date.now(),
  };

  channel.postMessage(event);
};

/*
 * Listen for events coming from another tab.
 */
export const subscribeRealtimeEvents = (
  listener: (event: RealtimeEvent) => void
): (() => void) => {
  if (!channel) {
    return () => undefined;
  }

  const handleMessage = (
    messageEvent: MessageEvent<RealtimeEvent>
  ) => {
    const event = messageEvent.data;

    /*
     * Ignore malformed events.
     */
    if (!event || !event.type) {
      return;
    }

    /*
     * Ignore events generated by this same tab.
     */
    if (event.sourceId === SOURCE_ID) {
      return;
    }

    listener(event);
  };

  channel.addEventListener(
    'message',
    handleMessage
  );

  /*
   * Return cleanup function.
   */
  return () => {
    channel.removeEventListener(
      'message',
      handleMessage
    );
  };
};

/*
 * Convenience methods.
 */
export const realtime = {
  dataChanged: (action?: string) => {
    broadcastRealtimeEvent(
      'DATA_CHANGED',
      action
    );
  },

  authChanged: () => {
    broadcastRealtimeEvent(
      'AUTH_CHANGED'
    );
  },

  logout: () => {
    broadcastRealtimeEvent(
      'LOGOUT'
    );
  },
};